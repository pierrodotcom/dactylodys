import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const OUT_DIR = 'src/lib/generated';
const PRIMITIVES = 'tokens/primitives.tokens.json';
const SEMANTIC = 'tokens/semantic.tokens.json';
const THEMES = { dark: 'tokens/themes/dark.tokens.json' };
const PREFIX = 'dd';

/** @param {Record<string, unknown>} config */
async function resolveTokens(config) {
	const dictionary = new StyleDictionary({
		usesDtcg: true,
		log: { verbosity: 'silent', warnings: 'error', errors: { brokenReferences: 'throw' } },
		platforms: { css: { transformGroup: 'css', prefix: PREFIX } },
		...config
	});
	await dictionary.hasInitialized;
	const { allTokens } = await dictionary.getPlatformTokens('css');
	return allTokens;
}

/** @param {{ name: string, $value: unknown }[]} tokens */
function declarations(tokens, indent) {
	return tokens.map((token) => `${indent}--${token.name}: ${token.$value};`).join('\n');
}

/** @param {string} name */
function camelCase(name) {
	return name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

const base = (await resolveTokens({ source: [PRIMITIVES, SEMANTIC] })).filter((token) =>
	token.filePath.endsWith(SEMANTIC)
);
const baseNames = new Set(base.map((token) => token.name));

const themes = {};
for (const [theme, file] of Object.entries(THEMES)) {
	const tokens = (await resolveTokens({ include: [PRIMITIVES, SEMANTIC], source: [file] })).filter(
		(token) => token.isSource
	);
	const foreign = tokens.filter((token) => !baseNames.has(token.name));
	if (foreign.length > 0) {
		throw new Error(
			`Theme "${theme}" redefines non-semantic tokens: ${foreign.map((t) => t.name).join(', ')}`
		);
	}
	themes[theme] = tokens;
}

const css = [
	'/* Generated by tools/build-tokens.js from tokens/. Do not edit. */',
	':root {',
	'\tcolor-scheme: light;',
	declarations(base, '\t'),
	'}',
	'',
	'@media (prefers-color-scheme: dark) {',
	"\t:root:not([data-theme='light']) {",
	'\t\tcolor-scheme: dark;',
	declarations(themes.dark, '\t\t'),
	'\t}',
	'}',
	'',
	":root[data-theme='dark'] {",
	'\tcolor-scheme: dark;',
	declarations(themes.dark, '\t'),
	'}',
	''
].join('\n');

const entries = base
	.map((token) => `\t${camelCase(token.name.slice(PREFIX.length + 1))}: '--${token.name}'`)
	.join(',\n');
const ts = [
	'// Generated by tools/build-tokens.js from tokens/. Do not edit.',
	'export const TOKEN_VARS = {',
	entries,
	'} as const;',
	'',
	'export type TokenKey = keyof typeof TOKEN_VARS;',
	'export type TokenVarName = (typeof TOKEN_VARS)[TokenKey];',
	''
].join('\n');

await mkdir(OUT_DIR, { recursive: true });
await writeFile(`${OUT_DIR}/tokens.css`, css);
await writeFile(`${OUT_DIR}/tokens.ts`, ts);
