import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { buildWebManifest } from './lib/web-manifest.js';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const LANGUAGE = 'fr';
const GENERATED_DIR = 'src/lib/generated';

/** @param {string} file */
async function readJson(file) {
	return JSON.parse(await readFile(file, 'utf8'));
}

const messages = await readJson(`messages/${LANGUAGE}.json`);
const tokens = await readJson(`${GENERATED_DIR}/token-values.json`);

// In `static/`, so that SvelteKit serves it at the root of the site and lists it for the service worker.
const manifest = buildWebManifest({ messages, tokens: tokens.light, language: LANGUAGE });
await writeFile('static/manifest.webmanifest', `${JSON.stringify(manifest, null, '\t')}\n`);

// The colour of the browser bar follows the colour scheme, which a manifest cannot say.
const themeColors = {
	light: tokens.light['color-surface-base'],
	dark: tokens.dark['color-surface-base']
};
await mkdir(GENERATED_DIR, { recursive: true });
await writeFile(
	`${GENERATED_DIR}/theme-colors.ts`,
	[
		'// Generated by tools/build-pwa.js from tokens/. Do not edit.',
		`export const THEME_COLORS = ${JSON.stringify(themeColors)} as const;`,
		''
	].join('\n')
);
